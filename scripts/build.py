"""Build offline Markdown views from canonical JSON. No web requests or dependencies.

Run from any directory: python /path/to/repo/scripts/build.py
Generated files are replaceable views. Hand-authored additions belong in notes/.
The preflight refuses to overwrite files without this generator's marker.
"""
from __future__ import annotations
import argparse
import csv
import io
import json
import os
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- GENERATED by scripts/build.py; edit canonical data, not this view. -->'
ROLES = {
    'exact_date': 'Day explicitly dated in the inspected source',
    'year_attested': 'Year attested; day not normalized',
    'conventional_date': 'Conventional or reconstructed year; review pending',
    'proposed_date': 'Proposed date, not an established exact-year event',
    'research_history': 'Research, publication, registration or digital-access history',
}

def load(name: str):
    return json.loads((ROOT/name).read_text(encoding='utf-8'))

def years(start: int, end: int) -> list[int]:
    if start == 0 or end == 0 or start > end:
        raise ValueError('Use ordered, nonzero historical years.')
    return [n for n in range(start, end+1) if n != 0]

def label(year: int) -> str:
    if year == 0:
        raise ValueError('No year zero in this repository.')
    return f'{abs(year)} {"BCE" if year < 0 else "CE"}'

def year_path(year: int) -> Path:
    if year == 0:
        raise ValueError('No year zero in this repository.')
    return Path('years')/('BCE' if year < 0 else 'CE')/f'{abs(year):04d}.md'

def rel(target: str | Path, origin: str | Path) -> str:
    return os.path.relpath(ROOT/target, (ROOT/origin).parent).replace(os.sep,'/')

def frontmatter(obj: dict) -> str:
    # JSON values are valid YAML scalars/flow collections; no YAML dependency.
    return '---\n' + '\n'.join(f'{k}: {json.dumps(v, ensure_ascii=False)}' for k,v in obj.items()) + '\n---\n'

def generated(body: str, meta: dict | None = None) -> str:
    return (frontmatter(meta) if meta else '') + MARKER + '\n\n' + body.strip() + '\n'

def source_refs(ids: list[str], origin: str) -> str:
    return ', '.join(f'[{s}]({rel(f"sources/{s}.md",origin)})' for s in ids) or 'No historical source claim; research task only.'

def make_outputs() -> tuple[dict[str,str], dict]:
    cfg=load('project.json'); ss=load('data/sources.json'); pp=load('data/periods.json')
    rr=load('data/records.json'); aa=load('data/audit.json'); cc=load('data/prior_chapter_crosswalk.json')
    sd={s['id']:s for s in ss}; out={}; yy=years(cfg['annual_start'],cfg['annual_end'])
    by_year={n:[] for n in yy}
    for r in rr:
        for l in r['year_links']:
            if l['year'] in by_year:
                by_year[l['year']].append((r,l['role']))
    for s in ss:
        p=f'sources/{s["id"]}.md'
        body=f'# {s["id"]} — {s["title"]}\n\n'
        body+=f'**Creator:** {s["creator"]}  \n**Type:** `{s["source_kind"]}`  \n**Inspection:** `{s["inspection"]}`  \n**Accessed:** {s["accessed"]}\n\n'
        body+=f'[Source / catalogue]({s["url"]})\n\n'
        if s['doi']: body+=f'**DOI:** `{s["doi"]}`\n\n'
        if s['publication_year']: body+=f'**Registered publication year:** {s["publication_year"]}; consult the note for version distinctions.\n\n'
        body+=f'## What was inspected\n\n{s["inspected_locator"]}\n\n{s["inspection_note"]}\n\n'
        body+=f'## Rights and copies\n\n{s["rights"]}\n\nNo third-party full text or image is bundled. A null checksum means no local source file was preserved; it is not an integrity check.\n\n'
        if s['alternative_urls']:
            body+='## Alternate discovery or metadata routes\n\n'+'\n'.join(f'- [Alternative {i+1}]({u})' for i,u in enumerate(s['alternative_urls']))+'\n\n'
        uses=[r for r in rr if any(c['source']==s['id'] for c in r['support'])]
        body+='## Linked evidence records\n\n'+ ('\n'.join(f'- [{r["id"]}: {r["title"]}](../records/{r["id"]}.md)' for r in uses) if uses else 'No seed evidence record uses this source yet; it may be a methodology source or collection lead.')
        out[p]=generated(body,{'id':s['id'],'human_review':s['human_review']})
    out['sources/README.md']=generated('# Source register\n\nInspection depth is not a quality score. A primary document can be biased; a catalogue can only establish what was actually inspected. All independent human review is pending.\n\n'+'\n'.join(f'- [{s["id"]} — {s["title"]}]({s["id"]}.md) — `{s["inspection"]}`' for s in ss))
    for r in rr:
        p=f'records/{r["id"]}.md'
        body=f'# {r["id"]} — {r["title"]}\n\n{r["claim"]}\n\n'
        body+=f'**Evidence type:** `{r["evidence_type"]}`  \n**Geographic relation:** `{r["scope_relation"]}`  \n**Places:** {"; ".join(r["places"]) or "Global context, not a local site"}\n\n'
        body+=f'## Date as represented\n\n```json\n{json.dumps(r["date"],ensure_ascii=False,indent=2)}\n```\n\n'
        if r['other_dates']:
            body+='Other, separately typed dates:\n\n```json\n'+json.dumps(r['other_dates'],ensure_ascii=False,indent=2)+'\n```\n\n'
        body+=f'## Limitations\n\n{r["caveat"]}\n\n'
        body+='## Evidence and locators\n\n'+'\n'.join(f'- [{c["source"]}](../sources/{c["source"]}.md), {c["locator"]}. Inspection: `{sd[c["source"]]["inspection"]}`.' for c in r['support'])+'\n\n'
        body+='## Navigation\n\n'+'; '.join(f'[{x}](../periods/{x}.md)' for x in r['periods'])+'\n\n'
        if r['year_links']:
            body+='; '.join(f'[{label(x["year"])}]({rel(year_path(x["year"]),p)}) — {ROLES[x["role"]]}' for x in r['year_links'])+'\n\n'
        body+=f'## Review and authorship\n\n{r["authoring"]}\n\n**Independent human review:** {r["human_review"]}. **Created / updated:** {r["created"]} / {r["updated"]}.\n\n{r["rights"]}'
        out[p]=generated(body,{'id':r['id'],'status':r['status'],'human_review':r['human_review']})
    out['records/README.md']=generated('# Evidence records\n\nThese are attributed, limited seed records. A research publication is not the historical event it discusses.\n\n'+'\n'.join(f'- [{r["id"]} — {r["title"]}]({r["id"]}.md)' for r in rr))
    for p in pp:
        path=f'periods/{p["id"]}.md'
        body=f'# {p["id"]} — {p["title"]}\n\n**Window:** {p["display_window"]}.\n\n**Question:** {p["central_question"]}\n\n'
        body+='## Evidence presently available in this seed\n\n'+p['established_in_this_pass']+'\n\n'
        body+='Source routes: '+source_refs(p['sources'],path)+'.\n\n'
        body+='## What this does not establish\n\n'+p['limitations']+'\n\n'
        body+='## Research tasks\n\n'+'\n'.join(f'- [ ] {t}' for t in p['research_tasks'])+'\n\n'
        body+='## Canonical seed records\n\n'
        ps=[r for r in rr if p['id'] in r['periods']]
        body+=('\n'.join(f'- [{r["id"]} — {r["title"]}](../records/{r["id"]}.md)' for r in ps) if ps else 'No canonical evidence record has been entered for this dossier yet.')+'\n\n'
        body+='## Coverage note\n\nThis is an open research dossier, not an exhaustive era narrative. Its window is an editorial retrieval aid and can overlap other dossiers. Primary evidence, source dates and interpretative disputes remain explicit. Human specialist review is pending.'
        out[path]=generated(body,{'id':p['id'],'kind':p['kind'],'coverage':'seed_or_open_dossier'})
    out['periods/README.md']=generated('# Era and period dossiers\n\nThe first twelve dossiers organize deep time and prehistory. Seven overlapping editorial windows connect the documentary periods to annual navigation. These are not a claim that all districts followed the same sequence.\n\n'+'\n'.join(f'- [{p["id"]} — {p["title"]}]({p["id"]}.md)' for p in pp))
    for i,y in enumerate(yy):
        p=year_path(y).as_posix(); entries=by_year[y]
        status='seed_index' if entries else 'unresearched'
        body=f'# {label(y)}\n\n'
        nav=[]
        if i: nav.append(f'[← {label(yy[i-1])}]({rel(year_path(yy[i-1]),p)})')
        nav.append('[Year index](../README.md)')
        if i+1<len(yy): nav.append(f'[{label(yy[i+1])} →]({rel(year_path(yy[i+1]),p)})')
        body+=' · '.join(nav)+'\n\n'
        body+='**Coverage:** '+('A small number of source-linked seeds; not a completed year history.' if entries else 'No year-specific seed has been entered. This year has not been exhaustively researched.')+'\n\n'
        if y == cfg['annual_end']:
            body+=f'**Partial year:** this release stops at {cfg["as_of"]}. No later event is implied.\n\n'
        for role,title in ROLES.items():
            rs=[r for r,k in entries if k==role]
            if rs:
                body+=f'## {title}\n\n'
                for r in rs:
                    body+=f'- [{r["id"]}: {r["title"]}](../../records/{r["id"]}.md). {source_refs([x["source"] for x in r["support"]],p)}.\n'
                body+='\n'
        body+='## Wider-period evidence — not an event assigned to this year\n\n'
        ps=[x for x in pp if x['annual_span'] and x['annual_span'][0] <= y <= x['annual_span'][1]]
        body+=('\n'.join(f'- [{x["id"]} — {x["title"]}](../../periods/{x["id"]}.md)' for x in ps) if ps else 'Consult the [period index](../../periods/README.md).')+'\n\n'
        body+='## Interpretation\n\nAn empty section is not proof that nothing happened or that no records survive. Century-dated and undated material stays in its period dossier; publication and discovery dates are separate from the events studied.\n\nAdd a canonical record in `data/records.json`, cite a source with a locator, and rebuild. Hand-authored research notes belong in `notes/`, not this generated page.'
        out[p]=generated(body,{'year':abs(y),'era':'BCE' if y<0 else 'CE','status':status,'as_of':cfg['as_of']})
    # Era-specific navigation lists keep the root year index readable.
    for era,group in [('BCE',[x for x in yy if x<0]),('CE',[x for x in yy if x>0])]:
        body=f'# {era} annual index\n\nGenerated navigation, not a measure of historical coverage.\n\n'
        for k in range(0,len(group),100):
            block=group[k:k+100]
            body+=f'## {label(block[0])} through {label(block[-1])}\n\n'+' · '.join(f'[{abs(x)}]({abs(x):04d}.md)' for x in block)+'\n\n'
        out[f'years/{era}/README.md']=generated(body)
    out['years/README.md']=generated(f'# Annual navigation\n\nThis release creates **{len(yy):,} annual Markdown files**, from {label(yy[0])} through {label(yy[-1])}, with no year zero. The starting boundary is editorial, not proof that writing began in 300 BCE.\n\n[Browse BCE](BCE/README.md) · [Browse CE](CE/README.md) · [Era and period dossiers](../periods/README.md)\n\nMost annual pages are unresearched navigation placeholders. A period link is not a year-specific event. See [coverage](../coverage/README.md).')
    auditbody='# Audit of the earlier conversation\n\n'
    auditbody+='This register separates factual claims, misleading implications, omissions, and proposed research topics. It is not a declaration that every topic is now fully verified. Repeated claims are consolidated; the 46-chapter crosswalk below preserves the full outline. "Pending" means the necessary primary evidence has not been inspected.\n\n'
    for a in aa:
        auditbody+=f'## {a["id"]} — {a["verdict"].replace("_"," ")}\n\n**Earlier claim or implication:** {a["earlier_claim"]}\n\n**Treatment:** {a["corrected_treatment"]}\n\n**Evidence route:** {source_refs(a["sources"],"audit/CHAT_AUDIT.md")}\n\n'
    auditbody+='## Crosswalk of every chapter in the earlier 46-chapter proposal\n\n| Chapter | Proposed subject | Dossier(s) | Audit status |\n|---|---|---|---|\n'
    for c in cc:
        auditbody+=f'| {c["chapter"]} | {c["title"]} | {c["dossiers"]} | {c["assessment"]} |\n'
    out['audit/CHAT_AUDIT.md']=generated(auditbody)
    stats=dict(as_of=cfg['as_of'],annual_files=len(yy),annual_pages_with_year_specific_seeds=sum(bool(v) for v in by_year.values()),
       annual_pages_without_year_specific_seeds=sum(not v for v in by_year.values()),canonical_records=len(rr),source_records=len(ss),
       era_dossiers=sum(p['kind']=='prehistory_and_deep_time' for p in pp),documentary_dossiers=sum(p['kind']!='prehistory_and_deep_time' for p in pp),
       audit_items=len(aa),prior_chapters_mapped=len(cc),human_reviewed_records=sum(r['human_review']=='approved' for r in rr),
       sources_by_inspection=dict(Counter(s['inspection'] for s in ss)),licensed_boundary_geometry_present=False,
       third_party_fulltexts_bundled=0,completed_collection_inventories=0,whole_web_completeness='not_claimed')
    out['coverage/stats.json']=json.dumps(stats,ensure_ascii=False,indent=2)+'\n'
    c=io.StringIO(); w=csv.writer(c,lineterminator="\n"); w.writerow(['era','year','file','year_specific_seed_links','status'])
    for y in yy: w.writerow(['BCE' if y<0 else 'CE',abs(y),year_path(y).as_posix(),len(by_year[y]),'seed_index' if by_year[y] else 'unresearched'])
    out['coverage/year-status.csv']=c.getvalue()
    body=f'''# Coverage — version {cfg['version']}

As of {cfg['as_of']}. These are repository counts, not estimates of the total historical record.

| Measure | This release |
|---|---:|
| Annual Markdown files | {len(yy):,} |
| Annual pages with at least one year-specific seed link | {stats['annual_pages_with_year_specific_seeds']} |
| Annual pages without a year-specific seed | {stats['annual_pages_without_year_specific_seeds']:,} |
| Canonical evidence records | {len(rr)} |
| Source cards, including catalogues and leads | {len(ss)} |
| Deep-time / prehistory dossiers | {stats['era_dossiers']} |
| Documentary-period dossiers | {stats['documentary_dossiers']} |
| Independent human-reviewed records | {stats['human_reviewed_records']} |
| Completed collection inventories | 0 |
| Third-party full texts or images bundled | 0 |
| Verified current boundary polygons | 0 |

The seed entries include research and publication milestones. They must not be reported as that many unique past events in the territory. Sources inspected only as abstracts or catalogues are clearly labelled. Empty years are unresearched, not historically empty.

No percentage for coverage of the entire internet is calculated. No source corpus has been completely inventoried. [Collection plan](../docs/CORPUS_PLAN.md) defines what an auditable completeness claim would require.

[Machine-readable statistics](stats.json) · [Year-by-year status](year-status.csv)
'''
    out['coverage/README.md']=generated(body)
    return out,stats

def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Compare generated views without changing files.')
    args=parser.parse_args()
    out,stats=make_outputs()
    mismatches=[p for p,t in out.items() if not (ROOT/p).exists() or (ROOT/p).read_text(encoding='utf-8')!=t]
    if args.check:
        if mismatches:
            print('Stale/missing generated views:',*mismatches[:15],sep='\n')
            return 1
        print(f'All {len(out)} generated files match canonical data.')
        return 0
    # Preflight ALL outputs before any write. Never overwrite hand-authored Markdown.
    for p in out:
        f=ROOT/p
        if f.exists() and f.suffix=='.md' and MARKER not in f.read_text(encoding='utf-8'):
            raise RuntimeError(f'Refusing to overwrite non-generated Markdown: {p}')
    for p,text in out.items():
        f=ROOT/p; f.parent.mkdir(parents=True,exist_ok=True)
        if f.exists() and f.read_text(encoding='utf-8')==text: continue
        tmp=f.with_suffix(f.suffix+'.tmp'); tmp.write_text(text,encoding='utf-8'); tmp.replace(f)
    print(json.dumps(stats,indent=2))
    print(f'Built {len(out)} generated files. No network requests made.')
    return 0

if __name__=='__main__':
    raise SystemExit(main())
