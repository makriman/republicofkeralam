def orphaned_outputs(out: dict) -> list[str]:
    """Generated-marker Markdown files under generated folders that no canonical item produces any more."""
    found=[]
    for d in GENERATED_DIRS:
        for f in sorted((ROOT/d).rglob('*.md')) if (ROOT/d).is_dir() else []:
            p=f.relative_to(ROOT).as_posix()
            if p not in out and MARKER in f.read_text(encoding='utf-8'):
                found.append(p)
    return found


def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Compare generated views without changing files.')
    args=parser.parse_args()
    out,stats=make_outputs()
    mismatches=[p for p,t in out.items() if not (ROOT/p).exists() or (ROOT/p).read_text(encoding='utf-8')!=t]
    orphans=orphaned_outputs(out)
    if args.check:
        if mismatches or orphans:
            if mismatches: print('Stale/missing generated views:',*mismatches[:15],sep='\n')
            if orphans: print('Orphaned generated views with no canonical source:',*orphans,sep='\n')
            return 1
        print(f'All {len(out)} generated files match canonical data.')
        return 0
    # Preflight ALL outputs before any write. Never overwrite hand-authored Markdown.
    for p in out:
        f=ROOT/p
        if f.exists() and f.suffix=='.md' and MARKER not in f.read_text(encoding='utf-8'):
            print(f'Refusing to overwrite non-generated Markdown: {p}. Nothing was written.',file=sys.stderr)
            return 2
    for p,text in out.items():
        f=ROOT/p; f.parent.mkdir(parents=True,exist_ok=True)
        if f.exists() and f.read_text(encoding='utf-8')==text: continue
        tmp=f.with_suffix(f.suffix+'.tmp'); tmp.write_text(text,encoding='utf-8',newline='\n'); tmp.replace(f)
    print(json.dumps(stats,indent=2,ensure_ascii=False))
    print(f'Built {len(out)} generated files. No network requests made.')
    if orphans:
        print('Orphaned generated views were left in place; remove them after checking:',*orphans,sep='\n')
        return 1
    return 0

if __name__=='__main__':
    raise SystemExit(main())
