def label_texts(data: dict | None = None) -> dict:
    """All label keys for this data: the static labels plus one per audit verdict."""
    out = dict(LABELS)
    for a in (data or {}).get('audit') or []:
        v = a.get('verdict') if isinstance(a, dict) else None
        if isinstance(v, str):
            out[f'verdict.{v}'] = ('inline', v.replace('_', ' '))
    return out


def load(name: str):
    return json.loads((ROOT/name).read_text(encoding='utf-8'))


def load_data() -> dict:
    return {'project': load('project.json'), 'sources': load('data/sources.json'), 'periods': load('data/periods.json'),
            'records': load('data/records.json'), 'audit': load('data/audit.json'), 'corpora': load('data/corpora.json'),
            'crosswalk': load('data/prior_chapter_crosswalk.json'), 'scope': load('geography/scope.json')}

def years(start: int, end: int) -> list[int]:
    if start == 0 or end == 0 or start > end:
        raise ValueError('Use ordered, nonzero historical years.')
    return [n for n in range(start, end+1) if n != 0]

def label(year: int) -> str:
    if year == 0:
        raise ValueError('No year zero in this repository.')
    return f'{abs(year)} {"BCE" if year < 0 else "CE"}'

def year_path(year: int) -> Path:
    if year == 0:
        raise ValueError('No year zero in this repository.')
    return Path('years')/('BCE' if year < 0 else 'CE')/f'{abs(year):04d}.md'

def rel(target: str | Path, origin: str | Path) -> str:
    return os.path.relpath(ROOT/target, (ROOT/origin).parent).replace(os.sep,'/')

def frontmatter(obj: dict) -> str:
    # JSON values are valid YAML scalars/flow collections; no YAML dependency.
    return '---\n' + '\n'.join(f'{k}: {json.dumps(v, ensure_ascii=False)}' for k,v in obj.items()) + '\n---\n'


_SINGLE_LINK = re.compile(r'\[([^\]]*)\]\(([^)]*)\)')


def combine(kind: str, ml: str, en: str) -> str:
    """Join Malayalam (first) and English (second) for one unit of text."""
    if kind == 'heading':
        h = re.match(r'#+ ', en).group(0)
        return f'{h}{ml[len(h):]} / {en[len(h):]}'
    if kind == 'bold':
        return f'**{ml[2:-2]} / {en[2:-2]}**'
    if kind == 'bracket':
        return f'[{ml[1:-1]} / {en[1:-1]}]'
    if kind == 'table_row':
        m = ml.strip().strip('|').split('|'); e = en.strip().strip('|').split('|')
        return '| ' + ' | '.join(f'{a.strip()} / {b.strip()}' for a, b in zip(m, e)) + ' |'
    if kind == 'block':
        return f'{ml}\n\n{en}'
    if kind == 'line':
        return f'{ml}  \n{en}'
    if kind == 'list':
        return f'{ml}  \n  {en}'
    ma, ea = _SINGLE_LINK.fullmatch(ml), _SINGLE_LINK.fullmatch(en)
    if ma and ea and ma.group(2) == ea.group(2):
        return f'[{ma.group(1)} / {ea.group(1)}]({ea.group(2)})'
    return f'{ml} / {en}'


