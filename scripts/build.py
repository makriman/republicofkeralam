class Page:
    """Collects which translations one generated page used."""

    def __init__(self, tr: bilingual.Translations, labels: dict):
        self.tr = tr; self.labels = labels; self.used = []

    def L(self, key: str, **kw) -> str:
        kind, en = self.labels[key]
        en_text = en.format(**kw) if kw else en
        e = self.tr.get(f'scripts/build.py#{key}', en)
        if not e:
            return en_text
        self.used.append(e)
        return combine(kind, e['ml'].format(**kw) if kw else e['ml'], en_text)

    def T(self, key: str, en: str, kind: str = 'inline') -> str:
        e = self.tr.get(key, en)
        if not e:
            return en
        self.used.append(e)
        return combine(kind, e['ml'], en)

    def ml(self, key: str, en: str):
        e = self.tr.get(key, en)
        if e:
            self.used.append(e)
            return e['ml']
        return None

    def status(self):
        if not self.used:
            return None
        ai = any(e.get('ai_assisted', True) for e in self.used)
        reviewed = all(e.get('human_language_review') == 'approved' for e in self.used)
        return ai, reviewed

    def render(self, body: str, meta: dict | None = None) -> str:
        st = self.status()
        if st:
            ai, reviewed = st
            mm, me = NOTICE_METHOD[ai]; rm, re_ = NOTICE_REVIEW[reviewed]
            notice = (f'> മലയാളം ആദ്യം, ഇംഗ്ലീഷ് തുടർന്ന്. {mm}; {rm}. ഇംഗ്ലീഷ് പാഠമാണ് അടിസ്ഥാന ഡാറ്റ.\n>\n'
                      f'> Malayalam first, English second. {me} and {re_}. The English text remains the canonical data.')
            head, _, rest = body.strip().partition('\n\n')
            body = f'{head}\n\n{notice}\n\n{rest}'
            if meta is not None:
                meta = dict(meta)
                meta['translation_ml'] = ('ai_assisted' if ai else 'human_translated') + ('_human_review_recorded' if reviewed else '_human_review_pending')
        return (frontmatter(meta) if meta else '') + MARKER + '\n\n' + body.strip() + '\n'


def generated(body: str, meta: dict | None = None) -> str:
    return (frontmatter(meta) if meta else '') + MARKER + '\n\n' + body.strip() + '\n'


